const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
if (path.dirname(output) !== root || (fs.existsSync(output) && fs.lstatSync(output).isSymbolicLink())) throw new Error('Unexpected output directory');
fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output);
fs.copyFileSync(path.join(root, 'index.html'), path.join(output, 'index.html'));
for (const dir of ['assets','src']) fs.cpSync(path.join(root,dir),path.join(output,dir),{recursive:true});
fs.writeFileSync(path.join(output,'.nojekyll'),'');
